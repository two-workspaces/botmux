// Maps the Railway service variables onto botmux's own files on every boot.
// It never fails the boot: anything it can't use is logged with what to fix,
// and botmux still starts with its dashboard.
import { existsSync, mkdirSync, readFileSync, writeFileSync, renameSync, chmodSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { join } from 'node:path';

const HOME = process.env.HOME || '/data';
const DIR = join(HOME, '.botmux');
const BOTS = join(DIR, 'bots.json');
const PARKED = join(DIR, 'railway-parked-bots.json');
const env = (k) => (process.env[k] || '').trim();
const log = (m) => console.log(`[railway] ${m}`);

function writeSecure(path, text) {
  const tmp = `${path}.railway-tmp`;
  writeFileSync(tmp, text, { mode: 0o600 });
  chmodSync(tmp, 0o600);
  renameSync(tmp, path);
}
function readJson(path, fallback) {
  try { return JSON.parse(readFileSync(path, 'utf8')); } catch { return fallback; }
}

mkdirSync(DIR, { recursive: true, mode: 0o700 });
chmodSync(DIR, 0o700);   // botmux refuses a group/other-writable ~/.botmux
mkdirSync(join(HOME, 'projects'), { recursive: true });

// ── Dashboard login token ────────────────────────────────────────────────────
// botmux keeps its one dashboard credential in ~/.botmux/.dashboard-token.
// DASHBOARD_TOKEN (generated by the template) is written there on every boot,
// so changing the variable is how the token is rotated.
const tokenFile = join(DIR, '.dashboard-token');
const wanted = env('DASHBOARD_TOKEN');
if (wanted) {
  if (!/^[A-Za-z0-9._~-]{16,256}$/.test(wanted)) {
    log('DASHBOARD_TOKEN must be 16-256 letters, digits or - _ . ~ (it goes in a URL); keeping the current token.');
  } else if ((existsSync(tokenFile) ? readFileSync(tokenFile, 'utf8').trim() : '') !== wanted) {
    writeSecure(tokenFile, wanted);
  }
}
if (!existsSync(tokenFile) || !readFileSync(tokenFile, 'utf8').trim()) {
  writeSecure(tokenFile, randomBytes(32).toString('base64url'));
  log('DASHBOARD_TOKEN is empty: generated a dashboard token. Print the login link with: railway ssh -- botmux dashboard');
}
if (existsSync(tokenFile)) chmodSync(tokenFile, 0o600);

// ── Machine-wide settings in ~/.botmux/.env ──────────────────────────────────
// botmux restarts (from the dashboard, or a bot's own /restart) read this file,
// not the container environment, so the Railway settings live here. Only the
// marked block is rewritten; anything else in the file is left alone.
const publicUrl = (env('PUBLIC_URL') || (env('RAILWAY_PUBLIC_DOMAIN') ? `https://${env('RAILWAY_PUBLIC_DOMAIN')}` : '')).replace(/\/+$/, '');
const block = [
  '# >>> railway: rewritten on every boot from the service variables',
  `BOTMUX_DASHBOARD_PORT=${env('PORT') || '7891'}`,
  // Upstream lets anyone without the token read session and group lists; on a
  // public domain that is everyone, so the template turns it off.
  'BOTMUX_DASHBOARD_PUBLIC_READONLY=false',
  ...(publicUrl ? [`BOTMUX_PUBLIC_URL=${publicUrl}`] : []),
  '# <<< railway',
];
const envFile = join(DIR, '.env');
let envText = existsSync(envFile) ? readFileSync(envFile, 'utf8') : '';
envText = envText.replace(/# >>> railway[^\n]*\n[\s\S]*?# <<< railway\n?/g, '');
writeSecure(envFile, `${block.join('\n')}\n${envText.replace(/^\n+/, '')}`);
if (!publicUrl) log('No public domain yet: add one in Settings → Networking (port 7891) and redeploy, so card links point at it.');

// ── Bots ─────────────────────────────────────────────────────────────────────
const hosts = { feishu: 'https://open.feishu.cn', lark: 'https://open.larksuite.com' };
const domainVar = env('FEISHU_DOMAIN').toLowerCase();
const brand = ['lark', 'larksuite', 'international', 'global'].includes(domainVar) ? 'lark' : 'feishu';
if (domainVar && !['feishu', 'lark', 'larksuite', 'international', 'global', 'china', 'cn'].includes(domainVar)) {
  log(`FEISHU_DOMAIN="${domainVar}" is not feishu or lark; using feishu.`);
}

// Same check botmux runs before `botmux start`; these codes make it refuse to start.
async function check(appId, appSecret, b) {
  if (!appId || !appSecret) return 'invalid';
  try {
    const r = await fetch(`${hosts[b] || hosts.feishu}/open-apis/auth/v3/tenant_access_token/internal`, {
      method: 'POST', headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ app_id: appId, app_secret: appSecret }), signal: AbortSignal.timeout(10_000),
    });
    const body = await r.json();
    if (body.code === 0) return 'ok';
    if ([10003, 10012, 99991663].includes(body.code)) return 'invalid';
    return `code ${body.code}: ${body.msg || ''}`;
  } catch (e) {
    return `unreachable: ${e.message}`;
  }
}

let bots = readJson(BOTS, null);
if (!Array.isArray(bots)) {
  if (existsSync(BOTS)) log('~/.botmux/bots.json is not a JSON array; starting with no bots (old file kept as bots.json.bad).');
  if (existsSync(BOTS)) renameSync(BOTS, `${BOTS}.bad`);
  bots = [];
}
let parked = readJson(PARKED, []);
if (!Array.isArray(parked)) parked = [];

const appId = env('FEISHU_APP_ID');
const appSecret = env('FEISHU_APP_SECRET');
const owners = env('FEISHU_OWNER').split(/[,\s]+/).filter(Boolean);
if (appId || appSecret) {
  if (!appId || !appSecret) {
    log(`Set both FEISHU_APP_ID and FEISHU_APP_SECRET (only ${appId ? 'the ID' : 'the secret'} is set); no bot was added from the variables.`);
  } else {
    const result = await check(appId, appSecret, brand);
    if (result === 'invalid') {
      log(`${brand === 'lark' ? 'Lark' : 'Feishu'} rejected FEISHU_APP_ID ${appId} with this FEISHU_APP_SECRET. Copy both from the app's Credentials page (and check FEISHU_DOMAIN: feishu for China, lark for international). The bot was not started; the dashboard still runs.`);
    } else {
      if (result !== 'ok') log(`Could not confirm the ${brand} app credentials (${result}); starting the bot anyway, it retries the connection.`);
      let bot = bots.find((b) => b && b.larkAppId === appId);
      if (!bot) {
        const p = parked.findIndex((b) => b && b.larkAppId === appId);
        if (p >= 0) { bot = parked.splice(p, 1)[0]; bots.push(bot); log(`Restored the parked bot ${appId}.`); }
      }
      if (!bot) {
        const cli = env('BOT_CLI') || 'claude-code';
        bot = {
          larkAppId: appId,
          cliId: /^[a-z0-9-]+$/.test(cli) ? cli : 'claude-code',
          workingDir: '~/projects',
          defaultWorkingDir: '~/projects',
        };
        bots.push(bot);
        log(`Added bot ${appId} (${bot.cliId}) from the variables. Later changes to it in the dashboard are kept; BOT_CLI only applies when the bot is first added.`);
      }
      bot.larkAppSecret = appSecret;
      bot.brand = brand;
      if (owners.length) {
        bot.allowedUsers = Array.isArray(bot.allowedUsers) ? bot.allowedUsers : [];
        for (const o of owners) if (!bot.allowedUsers.includes(o)) bot.allowedUsers.push(o);
      }
    }
  }
}

// A bot Feishu rejects makes `botmux start` refuse to start at all, taking the
// dashboard down with it. Park such bots in railway-parked-bots.json instead;
// a parked bot comes back by itself once its credentials work again.
const keep = [];
for (const b of bots) {
  if (b && (!b.larkAppId || !b.larkAppSecret || (await check(b.larkAppId, b.larkAppSecret, b.brand === 'lark' ? 'lark' : 'feishu')) === 'invalid')) {
    log(`Bot ${b.larkAppId || '(no app ID)'} has credentials Feishu/Lark rejects; parked it in ~/.botmux/railway-parked-bots.json so the rest of botmux can start. Fix FEISHU_APP_SECRET (or set the bot up again in the dashboard).`);
    parked = parked.filter((x) => x.larkAppId !== b.larkAppId);
    parked.push(b);
  } else keep.push(b);
}
for (const b of [...parked]) {
  if (b.larkAppId && b.larkAppSecret && (await check(b.larkAppId, b.larkAppSecret, b.brand === 'lark' ? 'lark' : 'feishu')) === 'ok'
      && !keep.some((k) => k.larkAppId === b.larkAppId)) {
    keep.push(b);
    parked = parked.filter((x) => x !== b);
    log(`Bot ${b.larkAppId} works again; restored it from the parked list.`);
  }
}
writeSecure(BOTS, `${JSON.stringify(keep, null, 2)}\n`);
if (parked.length) writeSecure(PARKED, `${JSON.stringify(parked, null, 2)}\n`);
else if (existsSync(PARKED)) writeSecure(PARKED, '[]\n');

for (const b of keep) {
  if (!Array.isArray(b.allowedUsers) || !b.allowedUsers.length) {
    log(`Bot ${b.larkAppId} has no admin (allowedUsers): anyone who can see the app in ${b.brand === 'lark' ? 'Lark' : 'Feishu'} can use it and run commands. Set FEISHU_OWNER to your work email or phone.`);
  }
}
if (!keep.length) {
  log('No bot yet. Open the dashboard and use "Create bot" (scan with the Feishu app), or set FEISHU_APP_ID and FEISHU_APP_SECRET.');
}

// ── Codex: its sandbox can't start on Railway ────────────────────────────────
// Codex's Linux sandbox (bubblewrap) needs user namespaces, which Railway's
// runtime refuses. botmux already starts Codex without it; this default only
// matters for `codex` run by hand over railway ssh. Written once, so edits stick.
const codexDir = join(HOME, '.codex');
mkdirSync(codexDir, { recursive: true });
if (!existsSync(join(codexDir, 'config.toml'))) {
  writeFileSync(join(codexDir, 'config.toml'), [
    "# Written by the Railway template on first boot. Codex's own sandbox cannot start",
    "# in Railway's containers (no user namespaces), so it runs unsandboxed in the container.",
    'sandbox_mode = "danger-full-access"',
    'approval_policy = "on-request"',
    '',
  ].join('\n'));
}

// ── Claude Code: accept ANTHROPIC_API_KEY without asking ─────────────────────
// Interactive Claude Code asks once whether to use a key it finds in the
// environment, and a botmux session would wait on that question. Claude keeps
// the answer as the key's last 20 characters in ~/.claude.json.
const anthropicKey = env('ANTHROPIC_API_KEY');
if (anthropicKey) {
  const claudeJson = join(HOME, '.claude.json');
  const data = readJson(claudeJson, {});
  data.hasCompletedOnboarding = true;
  const r = (data.customApiKeyResponses ||= { approved: [], rejected: [] });
  r.approved ||= []; r.rejected ||= [];
  const tail = anthropicKey.slice(-20);
  if (!r.approved.includes(tail)) r.approved.push(tail);
  r.rejected = r.rejected.filter((x) => x !== tail);
  writeSecure(claudeJson, `${JSON.stringify(data, null, 2)}\n`);
}

log(`dashboard:${publicUrl || `http://<domain>:${env('PORT') || '7891'}`}/?t=<DASHBOARD_TOKEN from the Variables tab> · bots: ${keep.length}${parked.length ? ` (${parked.length} parked)` : ''}`);
